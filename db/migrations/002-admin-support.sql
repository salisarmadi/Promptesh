-- ---------------------------------------------------------------------------
-- migration 002 — پشتیبانی از پنل مدیریت
-- ---------------------------------------------------------------------------
--
-- چرا این فایل لازم است؟
--     db/schema.sql با CREATE TABLE IF NOT EXISTS نوشته شده و روی دیتابیسی که
--     جدول‌هایش از قبل ساخته شده هیچ کاری نمی‌کند. پس برای دیتابیسِ موجود باید
--     ALTER زد. schema.sql هم جدا آپدیت شده تا نصب‌های تازه از اول کامل باشند.
--
-- سه تغییر، همه افزودنی و سازگار با گذشته:
--     ۱) categories.description  — فیلد توضیح که پنل مدیریت می‌خواهد
--     ۲) جدول admin_activity     — تا «فعالیت‌های اخیر» داشبورد داده‌ی واقعی باشد
--     ۳) images.updated_at       — تا ستون «آخرین ویرایش» در فهرست تصاویر واقعی باشد
--
-- هیچ ستونی حذف یا تغییر نوع نمی‌دهد و هیچ قید NOT NULL روی داده‌ی موجود
-- نمی‌گذارد، پس سایت عمومی حتی یک کوئری‌اش هم عوض نمی‌شود. اگر این مهاجرت اجرا
-- نشود، پنل مدیریت هم باید کار کند (کد خطای 42703 را می‌گیرد و آن بخش را
-- خاموش نشان می‌دهد) — ولی داشبورد بخشی از اطلاعاتش را از دست می‌دهد.
--
-- اجرا:
--     در کنسول SQL دیتابیس (Supabase → SQL Editor) کل همین فایل را اجرا کن.
--     بی‌خطر و idempotent است: چند بار اجرا کردنش مشکلی ایجاد نمی‌کند.

BEGIN;

-- ---------------------------------------------------------------------------
-- ۱) توضیح دسته‌بندی
-- ---------------------------------------------------------------------------
-- nullable و بدون CHECK: ۵ دسته‌ی موجود توضیحی ندارند و اجبار به پر کردنشان
-- یعنی مهاجرت روی داده‌ی فعلی می‌شکند. رشته‌ی خالی و NULL از نظر UI یکی‌اند و
-- سمت کد به هر دو یکسان نگاه می‌شود.
ALTER TABLE categories ADD COLUMN IF NOT EXISTS description TEXT;

COMMENT ON COLUMN categories.description IS 'توضیح کوتاه دسته؛ فقط در پنل مدیریت و در صورت نیاز برای سئوی صفحه دسته';

-- ---------------------------------------------------------------------------
-- ۲) گزارش فعالیت مدیر
-- ---------------------------------------------------------------------------
-- کارت «فعالیت‌های اخیر» در داشبورد بدون این جدول یا باید داده‌ی جعلی نشان دهد
-- یا باید حذف شود. راه سوم همین است: هر نوشتنِ پنل یک ردیف اینجا می‌گذارد.
--
-- چرا entity_id کلید خارجی نیست؟
--     مهم‌ترین رویدادی که ثبت می‌کنیم «حذف» است. اگر FK با ON DELETE CASCADE
--     می‌گذاشتیم، لحظه‌ی حذف تصویر همان ردیفِ گزارشش هم پاک می‌شد و دقیقاً
--     چیزی که می‌خواستیم نگه داریم از بین می‌رفت. با ON DELETE SET NULL هم
--     شماره‌ی رکورد را از دست می‌دادیم. پس عمداً بدون FK: این جدول یک لاگ
--     است، نه بخشی از مدلِ داده.
CREATE TABLE IF NOT EXISTS admin_activity (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action      TEXT NOT NULL CHECK (action IN ('create', 'update', 'delete')),
    entity_type TEXT NOT NULL CHECK (entity_type IN ('image', 'category', 'prompt')),
    -- شماره‌ی رکوردِ هدف. برای حذف هم پر می‌ماند (بدون FK، بالا توضیح داده شد).
    entity_id   BIGINT,
    -- خلاصه‌ی خواندنی برای نمایش در داشبورد، مثلاً عنوان تصویر یا نام دسته.
    -- در زمان نوشتن ثبت می‌شود چون بعد از حذف دیگر جایی برای خواندنش نیست.
    summary     TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE admin_activity IS 'لاگ نوشتن‌های پنل مدیریت؛ منبع کارت «فعالیت‌های اخیر» داشبورد';
COMMENT ON COLUMN admin_activity.summary IS 'خلاصه‌ی خواندنی در زمان رخداد؛ بعد از حذف رکورد، تنها ردِ باقی‌مانده است';

-- تنها کوئری این جدول «آخرین N رویداد» است.
CREATE INDEX IF NOT EXISTS admin_activity_created_at_idx
    ON admin_activity (created_at DESC);

-- ---------------------------------------------------------------------------
-- ۳) زمان آخرین ویرایش تصویر
-- ---------------------------------------------------------------------------
-- چرا trigger نگذاشتیم؟
--     یک trigger روی UPDATE، این ستون را برای هر نوشتنی بالا می‌برد — از جمله
--     اجرای دوباره‌ی scripts/import-content.mjs یا یک UPDATE دستی در کنسول
--     Supabase. آن‌وقت ستون می‌گوید «همه‌ی ۷۰۰ تصویر امروز ویرایش شدند» که
--     دروغ است. پس پنل خودش در همان UPDATE مقدارش را می‌گذارد و معنایش دقیق
--     می‌ماند: «آخرین ویرایشِ انسانی از طریق پنل».
--
-- NULL یعنی «از زمان این مهاجرت ویرایش نشده» و UI همان را نشان می‌دهد، نه
-- تاریخِ ساخت. پیش‌فرض now() نگذاشتیم چون ۷۰۰ ردیفِ قدیمی را با تاریخِ امروز
-- برچسب می‌زد.
ALTER TABLE images ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ;

COMMENT ON COLUMN images.updated_at IS 'آخرین ویرایش از طریق پنل مدیریت؛ NULL یعنی از ابتدا دست‌نخورده. بدون trigger، عمداً';

COMMIT;

