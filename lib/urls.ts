/**
 * ساختِ آدرسِ گالری از وضعیتِ فیلترها.
 *
 * چرا یک تابع مشترک و نه ساختنِ رشته در هر کامپوننت؟ چون فیلترها با هم جمع
 * می‌شوند: کاربری که «پرتره» را زده و بعد جستجو می‌کند، نباید دسته‌اش را از
 * دست بدهد. اگر هر کامپوننت خودش لینک بسازد، دیر یا زود یکی‌شان یک پارامتر را
 * جا می‌اندازد و فیلتر بی‌صدا پاک می‌شود. اینجا تنها جایی است که شکلِ آدرس
 * تعریف می‌شود، پس اضافه‌کردنِ محورِ بعدی (سبک) هم فقط همین فایل را عوض می‌کند.
 *
 * پارامترهای خالی حذف می‌شوند تا آدرسِ «همه‌چیز» همان «/» بماند و نه
 * «/?category=&q=» — هم تمیزتر است و هم برای سئو یک آدرسِ کانونیک می‌سازد.
 */

export type GalleryFilters = {
  /** slug دسته‌ی فعال. */
  category?: string | null;
  /** عبارت جستجوی فعال. */
  q?: string | null;
  /**
   * شماره‌ی صفحه، از ۱. مقدارِ ۱ در آدرس نوشته نمی‌شود.
   *
   * ⚠️ این تنها راهِ درستِ ساختنِ لینکِ صفحه است. اگر جایی «?page=1» تولید شود،
   * همان محتوا دو آدرس پیدا می‌کند («/» و «/?page=1») و گوگل یکی‌شان را
   * محتوای تکراری حساب می‌کند. حذفِ ۱ همین‌جا انجام می‌شود تا هیچ کامپوننتی
   * لازم نباشد یادش باشد.
   *
   * ترتیبِ پارامترها هم عمداً ثابت است (category، بعد q، بعد page): دو آدرس با
   * همان مقدارها ولی ترتیبِ متفاوت، برای گوگل دو آدرسِ جداگانه‌اند.
   */
  page?: number | null;
};

export function galleryHref(filters: GalleryFilters = {}): string {
  const params = new URLSearchParams();
  if (filters.category) params.set("category", filters.category);
  if (filters.q) params.set("q", filters.q);
  if (filters.page && filters.page > 1) params.set("page", String(Math.trunc(filters.page)));
  const qs = params.toString();
  return qs.length > 0 ? `/?${qs}` : "/";
}

/**
 * ?page= را به یک عددِ صفحه‌ی قابل‌اعتماد تبدیل می‌کند.
 *
 * ورودی از URL می‌آید، پس هر چیزی می‌تواند باشد: «abc»، «-۳»، «2.7»، «1e9»،
 * آرایه (وقتی پارامتر دو بار در آدرس تکرار شده)، یا غایب. همه‌ی این‌ها به ۱
 * برمی‌گردند و نه به NaN؛ NaN در محاسبه‌ی offset یعنی «LIMIT 60 OFFSET NaN» که
 * کوئری را با خطا می‌خواباند.
 *
 * سقفِ ۱۰۰۰: جلوی «?page=99999999» را می‌گیرد، یعنی جلوی offsetهای بی‌معنا.
 *
 * ⚠️ این سقف فضای آدرس را محدود نمی‌کند: «?page=1001» و «?page=1002» هنوز دو
 * آدرسِ جداگانه‌اند که هر دو به ۱۰۰۰ گره می‌خورند و بعد ۴۰۴ می‌شوند — و هر
 * کدام پیش از آن ۴۰۴، کوئری‌های صفحه را اجرا می‌کند. اگر روزی این تبدیل به
 * فشارِ واقعی شد، راهِ درستش کوتاه‌کردنِ همان مسیر است (اول شمردن، بعد گرفتنِ
 * عکس‌ها) نه پایین‌آوردنِ این عدد.
 */
const MAX_PAGE = 1000;

/**
 * رقم‌های فارسی (۰۶F۰–۰۶F۹) و عربی (۰۶۶۰–۰۶۶۹) را به لاتین برمی‌گرداند.
 *
 * چرا لازم است: نوارِ صفحه‌بندی شماره‌ها را با Intl به رقمِ فارسی نشان می‌دهد
 * («۳»). کاربری که آدرس را دستی عوض می‌کند طبیعتاً همان رقمی را تایپ می‌کند که
 * دیده، ولی Number("۳") برابرِ NaN است و بی‌صدا به صفحه‌ی ۱ می‌افتاد. در یک
 * سایتِ فارسی این یک حالتِ واقعی است، نه فرضی.
 *
 * & 0xf کار می‌کند چون هر دو بازه با رقمِ صفر شروع می‌شوند و پشتِ‌سرِ هم‌اند.
 */
function toLatinDigits(raw: string): string {
  return raw.replace(/[۰-۹٠-٩]/g, (d) => String(d.charCodeAt(0) & 0xf));
}

export function parsePage(raw: string | string[] | undefined): number {
  const value = typeof raw === "string" ? Number(toLatinDigits(raw)) : Number.NaN;
  if (!Number.isFinite(value)) return 1;
  const page = Math.trunc(value);
  if (page < 1) return 1;
  return Math.min(page, MAX_PAGE);
}
