import type { MetadataRoute } from "next";

/**
 * robots.txt — قواعدِ خزیدن.
 *
 * ── چرا این‌قدر کوتاه است ──
 * چون کارِ اصلی جای دیگری انجام شده. هر صفحه‌ای که نباید فهرست شود، خودش در
 * generateMetadata «robots: { index: false }» می‌گذارد: نمای جستجو («?q=») در
 * «/» و در صفحه‌ی دسته، عکسِ بی‌پرامپت، دسته‌ی ناموجود، و کلِ /admin و
 * /admin/login. robots.txt نمی‌تواند جایگزینِ هیچ‌کدام شود.
 *
 * ── ⚠️ چرا هیچ Disallow ندارد ──
 * وسوسه‌ی طبیعی «Disallow: /admin» و «Disallow: /*?q=» است. هر دو اشتباه‌اند و
 * دلیلش یکی است: Disallow جلوی *خواندنِ* صفحه را می‌گیرد، نه جلوی فهرست‌شدنش.
 * آدرسی که خزنده نتواند بخواند، تگِ noindexش هم خوانده نمی‌شود، پس گوگل
 * می‌تواند همان آدرس را بی هیچ محتوایی در نتایج نگه دارد («No information is
 * available for this page»). یعنی Disallow روی صفحه‌ای که noindex دارد،
 * دقیقاً همان چیزی را خراب می‌کند که برای درستش گذاشته شده بود.
 *
 * صرفه‌جوییِ crawl budget هم بهانه‌ی ضعیفی است: /admin دو آدرس است و نمای
 * جستجو از هیچ لینکِ داخلیِ قابل‌خزیدنی آویزان نیست (چیپ‌های واژگان لینک‌اند،
 * ولی مقصدشان همان «?q=»ِ noindex است که follow دارد و بس).
 *
 * اگر روزی مسیری اضافه شد که واقعاً نباید *خوانده* شود (مثلاً یک endpointِ
 * سنگینِ گزارش‌گیری)، آن‌جا Disallow ابزارِ درستی است — و همان‌وقت این کامنت هم
 * باید عوض شود.
 *
 * ── چرا await connection() ندارد، برخلافِ sitemap.ts ──
 * این فایل به دیتابیس کار ندارد و خروجی‌اش فقط به یک متغیرِ محیطی بستگی دارد.
 * پس کش‌شدنش در build نه‌فقط بی‌خطر است، بلکه مطلوب: یک فایلِ ثابتِ چند بایتی.
 *
 * ⚠️ نتیجه‌اش این است که NEXT_PUBLIC_SITE_URL باید *پیش از build* روی Netlify
 * ست شده باشد. اگر بعد از deploy اضافه شود، خطِ Sitemap تا build بعدی نمی‌آید.
 * (همین حالا هم متغیر در .env.local نیست — یعنی خروجیِ فعلی بی خطِ Sitemap است.)
 */

const SITE_URL = process.env.NEXT_PUBLIC_SITE_URL?.trim().replace(/\/+$/, "") ?? "";

export default function robots(): MetadataRoute.Robots {
  return {
    rules: { userAgent: "*", allow: "/" },
    /**
     * خطِ Sitemap آدرسِ مطلق می‌خواهد، پس بی متغیرِ محیطی حذف می‌شود.
     *
     * نوشتنِ یک آدرسِ حدسی (مثلاً از هدرِ Host) وسوسه‌کننده بود ولی خطرناک:
     * روی دامنه‌های پیش‌نمایشِ Netlify، sitemapِ محیطِ آزمایشی به گوگل معرفی
     * می‌شد و کلِ سایتِ آزمایشی به فهرست می‌رفت.
     */
    ...(SITE_URL ? { sitemap: `${SITE_URL}/sitemap.xml` } : {}),
  };
}
