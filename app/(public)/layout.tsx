import { SiteChrome } from "@/app/_components/website/SiteChrome";

/**
 * چیدمانِ سایتِ عمومی.
 *
 * پرانتزِ دورِ نامِ پوشه یعنی «گروهِ مسیر»: (public) در آدرس ظاهر نمی‌شود.
 * app/(public)/page.tsx همان / است که قبلاً app/page.tsx بود — آدرس‌ها، لینک‌ها،
 * canonicalها و نتایجِ گوگل هیچ‌کدام عوض نشدند.
 *
 * کارِ اول: هدر و فوتر را از layout ریشه بگیرد و اینجا بگذارد، تا /admin آن‌ها
 * را به ارث نبرد.
 *
 * ── کارِ دوم: اسلاتِ modal ──
 * @modal یک «مسیرِ موازی» است. پوشه‌ی @modal در آدرس ظاهر نمی‌شود و سگمنت هم
 * نیست؛ فقط به این layout یک پراپِ دوم می‌دهد که هم‌زمان با children رندر
 * می‌شود. کاری که این ساختار ممکن می‌کند: کلیک روی کارتِ گالری آدرس را واقعاً
 * به /image/<id> عوض می‌کند، ولی children (خودِ گالری، با اسکرول و صفحه‌بندی‌اش)
 * دست‌نخورده می‌ماند و محتوای عکس در مودال روی آن می‌آید.
 *
 * ⚠️ ترتیبِ رندر مهم است: {modal} بعد از {children} می‌آید. مودال position:fixed
 * و z-50 است، پس ترتیبِ DOM روی دیده‌شدنش اثر ندارد — ولی روی ترتیبِ Tab اثر
 * دارد. با آمدنِ اول، کاربرِ کیبورد پیش از رسیدن به محتوا از یک ناحیه‌ی خالی
 * عبور می‌کرد.
 *
 * ⚠️ سه فایل دیگر برای درست‌کارکردنِ این اسلات لازم‌اند و حذفِ هرکدام یک باگِ
 * جداگانه می‌سازد: @modal/default.tsx (رفرش در آدرسِ بی‌مودال)،
 * @modal/[...catchAll]/page.tsx (بستنِ مودال با رفتن به آدرسِ دیگر)، و
 * @modal/(.)image/[id]/page.tsx (خودِ رهگیری). توضیحِ هرکدام در فایلِ خودش است.
 */
export default function PublicLayout({
  children,
  modal,
}: {
  children: React.ReactNode;
  modal: React.ReactNode;
}) {
  return (
    <SiteChrome>
      {children}
      {modal}
    </SiteChrome>
  );
}
